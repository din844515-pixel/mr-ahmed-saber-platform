create table if not exists public.platform_testimonials (
  id bigint generated by default as identity primary key,
  student_name text not null check (char_length(trim(student_name)) between 2 and 80),
  education_stage text not null check (char_length(trim(education_stage)) between 2 and 80),
  review_text text not null check (char_length(trim(review_text)) between 10 and 700),
  created_at timestamptz not null default now()
);

alter table public.platform_testimonials enable row level security;

drop policy if exists platform_testimonials_public_read on public.platform_testimonials;
create policy platform_testimonials_public_read
  on public.platform_testimonials for select to anon, authenticated using (true);

drop policy if exists platform_testimonials_public_insert on public.platform_testimonials;
create policy platform_testimonials_public_insert
  on public.platform_testimonials for insert to anon, authenticated
  with check (
    char_length(trim(student_name)) between 2 and 80
    and char_length(trim(education_stage)) between 2 and 80
    and char_length(trim(review_text)) between 10 and 700
  );

grant select, insert on public.platform_testimonials to anon, authenticated;
grant usage, select on sequence public.platform_testimonials_id_seq to anon, authenticated;
